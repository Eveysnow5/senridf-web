// 受発注デモ（バッチ対応）の固定プロンプト。端点はこの一種類の仕事しかしない
// （＝汎用 LLM として悪用させない、護りの一部）。
//
// 2026-09-14: 単一の「受注台帳(品名/数量/単価/金額)」固定から、**帳票の種類に合わせて
// 列を推論する**汎用抽出に変更。給与明細・注文書・請求書などを 1 つのツールで扱い、
// 端点側で複数ファイルの列を union して 1 枚の Excel に合并する（docs/lead-gen 参照）。
//
// 出力は JSON のみを要求し、demo-order-extract.js 側で頑健にパースする。

export function buildDemoOrderPrompt(docText) {
  return [
    'あなたは帳票の構造化アシスタントです。以下は帳票（注文書・給与明細・請求書など）のテキストです。',
    '明細レコードを抽出し、各レコードを「キー: 値」のオブジェクト（1行）として構造化してください。',
    '- 給与明細のような1名分の帳票は通常1レコード。注文書・請求書は明細行ごとに1レコード。',
    '- 列（キー）は帳票の内容に合わせて日本語で適切に付ける（例: 氏名・役員報酬・健康保険料、または 品名・数量・単価・金額）。',
    '- 値は原文どおり。金額は数字（カンマ可）。帳票に無い項目は作らない。推測で埋めない。',
    '- 同じ帳票内のレコードは同じキー構成にそろえる。',
    '出力は JSON のみ。前後に説明文やコードフェンス(```)を付けないこと。次の形式：',
    '{"rows":[{"キー":"値", "キー":"値"}]}',
    '',
    '--- 帳票テキストここから ---',
    docText,
    '--- 帳票テキストここまで ---',
  ].join('\n');
}
