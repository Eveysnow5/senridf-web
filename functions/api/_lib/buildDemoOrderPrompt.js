// 受発注デモの固定プロンプト。端点はこの一種類の仕事しかしない
// （＝汎用 LLM として悪用させない、護りの一部）。
// 出力は JSON のみを要求し、demo-order-extract.js 側で頑健にパースする。

export function buildDemoOrderPrompt(orderText) {
  return [
    'あなたは受発注業務のアシスタントです。以下は取引先から届いた注文書のテキストです。',
    '注文明細を抽出し、受注台帳の行として構造化してください。',
    '各行の項目は「品名」「数量」「単価」「金額」の4つ。',
    '数量・単価・金額は数値のみ（記号や単位は除く。不明な項目は空文字 "" にする）。',
    '注文書に含まれない情報は推測して埋めないこと。',
    '出力は JSON のみ。前後に説明文やコードフェンス(```)を付けないこと。次の形式：',
    '{"rows":[{"品名":"","数量":"","単価":"","金額":""}]}',
    '',
    '--- 注文書テキストここから ---',
    orderText,
    '--- 注文書テキストここまで ---',
  ].join('\n');
}
