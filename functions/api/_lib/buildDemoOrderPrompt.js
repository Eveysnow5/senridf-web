// 受発注デモの固定プロンプト。端点はこの一種類の仕事しかしない
// （＝汎用 LLM として悪用させない、護りの一部）。
//
// 2026-10-06: **固定列の受注台帳に戻した。** 09-14 に「帳票の種類に合わせて列を推論する」
// 汎用抽出へ広げたが、ページは「受注台帳」を約束しているのに、
//   ・列名がファイルごとに揺れる（品名/商品名）→ 合并した表がバラバラ
//   ・見出しの 得意先/注文日/注文番号 が各行に入らない（台帳で一番要る情報）
// という名と実の不一致があった。給与明細などの汎用化は「第1製品を磨き切ってから」の決定で保留。
//
// 列は LEDGER_COLUMNS で固定し、端点側（mergeRows）でもこの列に正規化する。
// モデルが余計な列を足しても、列名を外しても、表の形はコードが保証する
// （プロンプトの遵守に頼らない）。
//
// 「写す」だけで「計算」はしない：金額が注文書に無ければ空のまま。数量×単価を
// AI に掛けさせると、合っているかを業務知識なしに検証できなくなるため。

export const LEDGER_COLUMNS = [
  '受注日',
  '得意先',
  '注文番号',
  '品番',
  '品名',
  '数量',
  '単位',
  '単価',
  '金額',
  '納期',
  '備考',
];

export function buildDemoOrderPrompt(docText) {
  return [
    'あなたは受注台帳の作成アシスタントです。以下は取引先から届いた注文書のテキストです。',
    '注文書の明細行ごとに1レコードを作り、次の列（キー）だけを持つオブジェクトにしてください：',
    LEDGER_COLUMNS.join('・'),
    '- 受注日・得意先・注文番号は注文書の見出しの情報。全レコードに同じ値を入れる。',
    '  受注日＝注文日（発行日）。得意先＝注文書を発行した会社（発注者）。宛先の会社ではない。',
    '- 納期は明細ごとの指定があればそれ、無ければ見出しの納期。',
    '- 値は原文どおり写す。計算しない。推測で埋めない。注文書に無い項目は空文字 "" にする。',
    '- 小計・消費税・合計などの集計行は明細ではないので、レコードにしない。',
    '- 数量・単価・金額は数字部分だけ（カンマ可。円・¥ は付けない）。',
    '出力は JSON のみ。前後に説明文やコードフェンス(```)を付けないこと。次の形式：',
    '{"rows":[{"受注日":"…","得意先":"…","品名":"…"}]}',
    '',
    '--- 注文書テキストここから ---',
    docText,
    '--- 注文書テキストここまで ---',
  ].join('\n');
}
