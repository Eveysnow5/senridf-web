// PDF から取ったテキストの「康熙部首」を通常の漢字（日本の字形）に戻す。
//
// 何が起きるか（2026-10-06 SiliconFlow/Gemma のスモークテストで発覚）：
//   Chrome/Edge が印刷した PDF などでは、一部の漢字が**見た目が同じ別の文字**
//   （康熙部首 U+2F00–2FD5 / CJK 部首補助 U+2E80–2EF3）で埋め込まれる。
//   例：用→⽤(U+2F64)、黒→⿊(U+2FCA)、入→⼊(U+2F0A)、月→⽉(U+2F49)。
//   画面上は区別できないが、Excel の検索・VLOOKUP・並べ替えで**一致しない**。
//   Qwen はたまたま正規化して返したが、Gemma は「原文どおり」忠実に写す。
//   → モデルの気分に頼らず、送る前と返った後の両方でコードが直す。
//
// なぜ素の NFKC ではないか：NFKC は ⿊ を**中国字形の「黑」**に、⾭ を「靑」に変える。
//   日本の帳票では 黒・青 が正しいので、日本の字形が別にあるものだけ上書きする。
//   ⿓→龍 は上書きしない（龍は人名などで正規に使う。竜にすると名前を壊す）。
//   ⾾(鬥) も NFKC のまま：部首の字形を流用するのは字形が同じときだけで、闘≠鬥。
//
// 部首ブロック以外の文字には触らない（全角数字などは原文の書き方を尊重）。

// NFKC の結果を日本の字形に上書きするもの（キー＝部首の文字）。
const KANGXI_JP = {
  '⾭': '青', // ⾭ → 青（NFKC だと 靑）
  '⿆': '麦', // ⿆ → 麦（麥）
  '⿈': '黄', // ⿈ → 黄（黃）
  '⿊': '黒', // ⿊ → 黒（黑）
  '⿑': '斉', // ⿑ → 斉（齊）
  '⿒': '歯', // ⿒ → 歯（齒）
  '⿔': '亀', // ⿔ → 亀（龜）
};

// 部首補助ブロックは NFKC がほぼ効かないので、漢字一字として現れうるものだけ明示する。
// （偏や旁の形だけのもの〔⻖⻏ など〕は単独の漢字として出ないので対象外）
const SUPPLEMENT_JP = {
  '⺟': '母', // ⺟ → 母
  '⺠': '民', // ⺠ → 民
  '⻄': '西', // ⻄ → 西
  '⻑': '長', // ⻑ → 長
  '⻝': '食', // ⻝ → 食
  '⻤': '鬼', // ⻤ → 鬼
  '⻩': '黄', // ⻩ → 黄
  '⻫': '斉', // ⻫ → 斉（J-SIMPLIFIED EVEN）
  '⻭': '歯', // ⻭ → 歯（J-SIMPLIFIED TOOTH）
  '⻯': '竜', // ⻯ → 竜（J-SIMPLIFIED DRAGON：字形が竜なので竜）
  '⻲': '亀', // ⻲ → 亀（J-SIMPLIFIED TURTLE）
};

const RADICAL_RE = /[⺀-⻳⼀-⿕]/g;

export function normalizeJa(s) {
  if (typeof s !== 'string' || !s) return s;
  return s.replace(RADICAL_RE, (ch) => {
    if (KANGXI_JP[ch]) return KANGXI_JP[ch];
    if (SUPPLEMENT_JP[ch]) return SUPPLEMENT_JP[ch];
    const n = ch.normalize('NFKC');
    return n !== ch ? n : ch;
  });
}
