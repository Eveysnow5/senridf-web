// 文档分析的提示词构造。抽成纯函数是为了可单测——这段提示词已经改写过三次，
// 每次都可能不小心把上一次加的硬规则删掉。
//
// 历史：2026-08-11 用户上传华为 2025/2024 年报、问"处置荣耀产生的利润对财务报表
// 有多大影响"，拿到一篇通用年报综述，且其中出现了两类违规：
//   · "2020年出售荣耀可能产生长期投资收益" —— 「2020年出售荣耀」这个事实**不在
//     上传的两份年报里**，是模型自己的世界知识
//   · "极有可能是荣耀处置相关的递延收益确认进入尾声" —— 用推测填补数据缺口
// 规则当时已经写了"仅使用文件内数据"，但不够硬，而且综合报告模式里"分析洞察"
// 这种小节名本身就在邀请推测：数据缺失时模型倾向填满小节而不是留白。

/**
 * 被禁的推测性写法。**单一来源**：提示词从这里生成，评估基线也从这里取。
 *
 * 为什么必须只留一份：2026-08-13 基线首次实跑时发现，提示词禁了 8 个词，而
 * docs/eval/analysis-cases.json 里只抄了 6 个——漏掉的恰好是「通常包含」，而模型
 * 那次的最终结论正是「其他收益（**通常包含**政府补助）」。两份手抄的清单必然漂移，
 * 且漂移方向总是"基线比规则松"：于是基线全绿、规则其实已经被违反。
 */
export const BANNED_HEDGES = [
  '可能是',
  '极有可能',
  '或许',
  '推测',
  '通常包含',
  '一般而言',
  '按惯例',
  '结合常识',
];

/** 两态共用的硬规则。用户明确要求的两条（列出来源、找不到就说找不到）在这里。 */
const RULES_COMMON = `【核心规则 — 必须严格遵守，违反即为失败输出】

一、只用文件里的内容
1. 仅使用下方提供的文件内容中明确记载的信息。**禁止使用你自己知道的任何外部事实**——包括公司历史、行业惯例、公开新闻、以往年报、常识推断。
2. 具体反面例子（真实发生过）：文件是 2024/2025 年报，模型却写出"2020年出售荣耀…"。那个年份和事件不在文件里，属于外部知识，**绝对禁止**。

二、找到了 → 必须给出来源
3. **每一条关键信息都要标注来源**，不只是数字。格式：\`（文件N·章节名或表名）\`。
   例："营业利润 969.37 亿元（文件1·五年财务概要）"、"管理层称将聚焦核心业务（文件1·轮值董事长致辞）"。
4. 无法定位到具体章节的，至少写\`（文件N）\`。**给不出来源的信息不要写**——如果你说不清它是从哪看到的，那它很可能不是从文件里看到的。
4.1 若上文提供了【准则库】，那些条目**也是合法出处**，引用格式「（准则库·XXX）」。但它们只解释科目含义与列报规则，**不提供任何公司的任何数字**；数字一律来自上传的文件。
4.2 ⚠️ 准则库每条都附了「这一条**没有**说什么」。**不许越过那条边界**——例如"政府补助计入其他收益"不等于"其他收益就是政府补助"，把单向规则读成双向是本工具真实犯过的错。

三、找不到 → 就说找不到，不要猜
5. **禁止用推测填补数据缺口。** 具体禁止这些写法：${BANNED_HEDGES.map((w) => `"${w}"`).join('、')}——凡是用来替代一个查不到的数字或事实的，一律不许写。
6. 找不到时的正确做法：直接说明**缺什么、通常在年报的哪个章节能找到**。例："文件中未见处置荣耀的具体收益金额；该数据通常披露在『合并财务报表附注 — 处置子公司』一节，建议补充该章节。"
7. **"找不到"是一个完整、合格的回答。** 不要因为答案短就去凑长度、不要用其它数据拼一篇看起来充实的分析来掩盖关键数据的缺失。
8. 对已有数据做解读是允许的，但必须与事实分开写、并标明是你的判断（如"由此判断：…"），且不得把判断当成文件披露的事实。

四、区分"文件没有"和"我没看到"
9. ⚠️ 提供给你的内容可能是**按提问筛选出的片段**而非全文（文件标题后会注明字数）。因此：
   · 你确实看到了 → "文件中披露为 X（文件N·章节）"
   · 你没看到 → "所提供的片段中未包含该信息，可能存在于未提供的章节"
   **绝不要把"我没看到"写成"文件未披露"。** 这是本工具曾经犯过的错误。`;

/**
 * 多轮取页态的附加说明。见 docs/plans/2026-08-12-analysis-multiround-plan.md。
 *
 * 只在**有提问**时生效：综合分析没有可追查的问题，多轮无从收敛。
 * 不传 multiRound 时返回空串，此时整份 prompt 与单轮态**逐字节相同**——单轮是已知
 * 可用的路径，多轮不许给它带来任何回归（tests/build-analysis-prompt.test.mjs 钉住了这条）。
 *
 * ⚠️ **这一段里绝不能出现轮次号。** 隐式缓存按请求**前缀**匹配，而 system 排在最前面：
 * 早先这里写了「第 N/5 轮」，导致 system prompt 从第 993 个字符起每轮都不同，整个前缀
 * 失配——页面索引那 1.4 万 token **每轮都按全价重付**，缓存一次都没命中（命中价是
 * 原价的 1/8）。逐轮变化的部分全部挪到 buildRoundTail，摆在用户消息最末尾：那里在
 * 图像之后，本来就不进缓存前缀，而且是模型注意力最高的位置。
 *
 * ⚠️ 这里的 `NEED_PAGES:` 示例与 js/shared/parse-page-request.js 是同一份契约。
 * 测试会把这段文字里的示例真的喂给解析器——改了这边而没改那边，循环会安静地
 * 永远解析不出页码，然后每次都空转到轮数上限。
 */
function buildRoundBlock(question, opts) {
  if (!question || !opts.multiRound) return '';

  return `
【本次为多轮取页分析】
你看到的**不是全文**。你手上有两样东西：一份**页面索引**（每页一行：页码 + 该页开头
约 80 字），以及本轮渲染出来的那几页**页面图像**。索引只是目录级线索、**不是全文**——
索引某一行里没出现某个词，不代表那一页上没有它。

关于页码（这一条错了不会报错，只会安静地看错页）：
· 索引每行形如 \`p86 (印刷84) | 9 其他净收支 政府补助 …\`。
  \`p86\` 是 PDF 里的第 86 页；\`(印刷84)\` 是这一页上印着的页码——年报有封面和扉页，
  两套页码常差几页。
· **索要页面时只用 p 后面那个数**（此例为 86）。写成 84 会取到另一页，而 84 同样是
  一个合法页码，**取错了不会报错、你也察觉不到**。
· 但**引用来源时两个都写**：\`（文件1·p86 印刷84）\`，这样人才能在纸本或 PDF 上核对。

你还可以先**查找**（零成本，建议在拿不准该看哪页时先用）：
   FIND: 文件3:Statements of Income,Government grants
   FIND: 其他收益,补助金          ← 不写文件号就是所有文件都找
   会返回每个词命中的页码、次数和一小段上下文。**查找和索要可以同一轮发出。**
⚠️ **索引只是每页开头 80 字**，一份文件的开头几页往往是封面、翻译声明、目录——
   **不能代表整份文件**。判定"某份文件没有某样东西"之前，要么逐行看完那份文件的
   整段索引，要么先 FIND 一次。凭开头几行就放弃索要，是本工具真实犯过的错。

本轮你可以：
① 还需要看别的页 → 用**单独成行**的一行指令索要（可一次要多份文件的多页）：
   NEED_PAGES: 文件1:86,87 文件2:84
   这一行之后可以另起一段说明你为什么要这几页。
② 已经够了 → 以 \`ANSWER:\` 开头，直接给出最终回答。

结转规则（多轮的关键，不遵守会让后面几轮建在错误之上）：
· 每一轮的发现只以**文字**带到下一轮，**图像不会重发**。下一轮的你看不到这张图了。
· 所以凡是在图里读到的关键数字和句子，**必须当场摘录原文**并标明页码，例如：
  \`（文件1·p86）"处置子公司及业务形成的金融工具的公允价值变动 (ii) – 55,853"\`
· **摘原文，不要只写结论。** 这一轮若读错一个数字，原文引文能让后面几轮发现它，
  而一句结论不能——错误会一路传下去且无从察觉。
· 已经摘录过的页不要重复索要，把预算留给还没看过的页。
`;
}

/**
 * 逐轮变化的那一小段，摆在用户消息**最末尾**。
 *
 * 为什么不放 system：见 buildRoundBlock 的注释——system 在请求最前面，逐轮变化会让
 * 隐式缓存的整个前缀失配。这里在图像之后，本来就不进缓存前缀，而且是注意力最高的位置，
 * 「最后一轮必须作答」放这儿反而更容易被遵守。
 *
 * @param {number} round 当前轮次（1 起）
 * @param {number} maxRounds 轮数上限
 * @returns {string}
 */
export function buildRoundTail(round, maxRounds) {
  const n = Number.isFinite(round) ? round : 1;
  const m = Number.isFinite(maxRounds) ? maxRounds : 5;
  if (n >= m) {
    return [
      '='.repeat(40),
      '',
      `【第 ${m}/${m} 轮 — 最后一轮】`,
      '本轮**不能再索要页面**。请用现有信息作答，以 `ANSWER:` 开头。',
      '仍然缺失的部分照核心规则第三节处理：说明缺什么、通常在年报哪个章节能找到，**不要猜**。',
      '',
      '⚠️ **区分"转述数字"和"解释数字"。** 转述可以直接写；而说明这个数字**是什么、',
      '为什么、意味着什么**，必须能指到某一页的原文，指不到就写「文件只显示 X，其',
      '构成/成因未披露」。',
      '这一条禁的是**行为**，不是措辞——换个说法绕过去同样违规。**唯一的判据是：',
      '这句话能不能指到文件里的某一页。**',
      '前几轮你若写过"只能报告这个数字的存在"之类的保留，**这一轮不许把它悄悄去掉**：',
      '看到的证据没有增加，结论的确定性就不该增加。',
      '',
      '⚠️ **覆盖**：用户上传的每一份文件、问题涉及的每一个期间，都要有交代——哪怕',
      '交代的是「该文件/该期间未取到相关页面，无法回答」。**默默略过等于让用户以为',
      '你看过了。**',
    ].join('\n');
  }
  return [
    '='.repeat(40),
    '',
    `【第 ${n}/${m} 轮】还可以再索要 ${m - n} 轮。`,
    '还需要看别的页 → 用**单独成行**的 `NEED_PAGES:` 指令索要；已经够了 → 以 `ANSWER:` 开头作答。',
    '⚠️ 别为了多看几页而拖延：能答就答。每多一轮，你都要多等一次，而且已读过的图不会再出现。',
  ].join('\n');
}

/**
 * 构造 system 提示词。有提问走针对性回答，无提问走综合报告。
 * @param {string} question 用户提问（已 trim），空串表示未提问
 * @param {{multiRound?:boolean}} [opts] multiRound 为真才插入多轮说明（**不含轮次号**）
 * @returns {string}
 */
export function buildAnalysisSystemPrompt(question, opts = {}) {
  const roundBlock = buildRoundBlock(question, opts);
  if (question) {
    return `你是专业的财务分析师。用户有一个**具体问题**，你的任务是回答那个问题，不是产出通用年报综述。

${RULES_COMMON}
${roundBlock}
【本次任务形态 — 针对性回答】
- **开门见山直接回答问题。** 第一段就给结论，不要先铺垫公司概况、不要先列指标总表。
- 只呈现支撑该结论所必需的数据与推理。与问题无关的板块、区域、战略分析**一律不要写**，即使文件里有。
- **不要**输出【关键指标概览】总表、不要逐项分析 MD&A、不要罗列"财务异同点总结"——除非这些正是问题本身所问。
- 结论不确定时说清不确定的来源（数据缺失／口径差异／需要未提供的章节），并只列出**为回答这个问题**还缺哪些资料。
- 篇幅服从问题：一个具体问题能用三段说清就写三段。**不追求大而全。**

【追查方法 — 财报里的答案通常不在正文】
这套方法来自一次真实的人工分析（2026-08-11），请按同样的思路走：
1. **金额在附注里，不在正文。** 处置损益、非经常性项目、公允价值变动这类，正文
   （致辞／MD&A／五年概要）通常只有汇总数或压根不提。先找报表行项目，再找它的附注。
2. **看到行项目带「附注 (i)/(ii)」这类引用，必须去读对应附注。** 行项目只给数字，
   附注才说明这个数字是什么构成的。
3. ⚠️ **同一个附注编号在不同年度的年报里可能解释的是不同事项。** 不要假定含义相同。
   真实案例：「处置子公司及业务形成的金融工具的公允价值变动」这一行，2024 年报的
   附注归因于"以前年度出售荣耀业务"，而 2025 年报的同一行附注归因于"以前年度出售
   部分服务器业务"——**是两件不同的事**。逐年读各自的附注，分别说明。
4. **某一年的附注没提到问题里的关键词，不等于那一年没有相关影响。** 正确做法是：
   先确认同一行项目在该年是否有金额，再说明该年的附注把它归因于什么。若归因对象
   与问题所问不同，明确指出这一点（例："2025 年该行金额为 X，但附注归因于服务器
   业务而非荣耀"），而不是简单答"未披露"。
5. 跨年对比时，**以行项目名称对齐**，而不是以附注编号对齐——编号会变。
6. ⚠️ **PDF 表格抽取后，行名和数字常常被拆成两段**：先是一串行名，然后才是一串
   数字。例如「政府补助 处置子公司及业务形成的金融工具的公允价值变动 代扣个人
   所得税手续费返还 …」之后才出现「(i) 5,717 7,327 (ii) – 55,853 692 614 …」。
   读这类表格时必须**按顺序位置对齐**行名与数字，并注意：
   · 表头会标明列的年份顺序（如「2024年 2023年」），别把两列搞反；
   · 「–」表示该年为零/无，不是缺失数据；
   · 对齐后**用附注文字交叉验证**你的读数（附注通常会重复关键金额或说明构成）。
   若无法可靠对齐，明确说明"该表格抽取后行列错位，无法可靠读数"，**不要猜数字**。`;
  }

  return `你是专业的财务分析师，擅长解读财务报告、MD&A 及多份财务文件的交叉对比。

${RULES_COMMON}

【本次任务形态 — 综合分析（用户未指定问题）】
- 开头先输出一张【关键指标概览】Markdown 表格：多份文件时列为各文件/主体、行为关键指标（营业收入、净利润、毛利率、同比增长率、总资产、经营现金流等，按实际披露选取），缺披露的填"⚠️未披露"；单份文件时用两列（指标 | 数值）。表格之后再展开文字分析。
- 重点关注：财务数据（收入、利润、资产、现金流）、经营指标、关键比率。
- 分析 MD&A 中的管理层洞察、经营策略与风险因素。
- 明确指出各对象的财务异同点：营收规模、盈利能力、增长率、关键指标对比。
- 结尾输出【需要补充的信息清单】，列出影响分析质量的缺失数据项。
- ⚠️ 即使是综合分析，上面第三节的规则同样适用：**没有数据的小节就写"文件中未见相关披露"，不要为了填满结构而推测。**`;
}

/**
 * 构造 user 消息。
 *
 * ⚠️ 顺序有讲究，不要"为了突出问题"把问题挪到开头：隐式缓存按请求前缀匹配
 * （命中价 1.5 元/百万，是输入原价的 1/8），文档在前 → 同一批文档换问题时前缀
 * 不变、命中缓存，追问成本从约 1.5 元降到约 0.4 元。而模型对结尾内容的注意力
 * 本来就高，问题放最后不吃亏，用分隔线和明确措辞强调即可。
 *
 * @param {string} docContext 已拼好的文件内容
 * @param {string} question 用户提问（已 trim），空串表示未提问
 * @returns {string}
 */
/**
 * 问题块：分隔线 + 提问 + 那几条硬要求。
 *
 * 单独导出是因为图像路径要把它作为多模态数组的**最后一个 text part** 追加在图片
 * 之后。之前那里是 `userMessage.slice(userMessage.indexOf('='.repeat(40)))`，有两个
 * 毛病：① 切的是**第一条**分隔线，混合场景（PDF 走图像 + xlsx 走文本）会把命中
 * 片段整块重复一遍；② 无提问时 indexOf 返回 -1，slice(-1) 只剩最后一个字符。
 *
 * @param {string} question 已 trim 的提问
 * @param {'text'|'image'} [mode] 参考资料的形态。'image' 时最后那句"下结论前先看完
 *   上面的东西"必须指向页面图像——图像路径没有【命中最强片段】（highlights 只从
 *   文本类文件里摘），照抄文本版的措辞会让模型去找一个不存在的小节。
 * @returns {string}
 */
export function buildQuestionTail(question, mode = 'text') {
  const lookHere =
    mode === 'image'
      ? '⚠️ 判定"查不到"之前，必须先逐页看完上面的页面图像，尤其是表格里的每一行——那里通常就是答案所在。'
      : '⚠️ 判定"查不到"之前，必须先逐条读完上面的【命中最强片段】——那里通常就是答案所在。';
  return [
    '='.repeat(40),
    '',
    '【本次必须回答的问题】',
    question,
    '',
    mode === 'image'
      ? '上面的页面图像仅是参考资料。请直接回答这个问题，不要写成通用分析报告。'
      : '上面的文件内容仅是参考资料。请直接回答这个问题，不要写成通用分析报告。',
    '回答里每条关键信息都要带来源；查不到的就明确说查不到，不要猜。',
    lookHere,
  ].join('\n');
}

export function buildAnalysisUserMessage(docContext, question, highlightBlock = '') {
  if (question) {
    // highlightBlock 放在文档之后、问题之前：既不破坏"文档在前"的缓存前缀，
    // 又贴着问题、处在模型注意力最高的位置。它是上面片段的子集（重复一份），
    // 刻意冗余——2026-08-11 实测证明，只靠"内容在里面"不足以让模型看见。
    const parts = ['以下是供你参考的财务文件内容：', '', docContext, ''];
    if (highlightBlock) {
      parts.push(
        '='.repeat(40),
        '',
        '【与本次提问关键词命中最强的片段（已从上文摘出，重点看这里）】',
        highlightBlock,
        '',
      );
    }
    parts.push(buildQuestionTail(question));
    return parts.join('\n');
  }

  return [
    '以下是需要分析的财务文件内容（包含财务报表和MD&A）：',
    '',
    docContext,
    '',
    '---',
    '',
    '分析要求：请对以上财务报告进行深度对比分析，重点关注财务指标、增长趋势、盈利能力和管理层对经营的分析。',
  ].join('\n');
}
